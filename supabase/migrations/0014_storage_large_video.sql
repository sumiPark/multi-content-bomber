-- 0014 — 'media' 버킷 업로드 한도 100MB → 1GB.
--
-- 유튜브·인스타에 대용량 영상(최대 800MB)을 올리기 위한 상향.
-- 1GB로 잡은 건 인스타 릴스 공식 한도가 1GB이기 때문 — UI 한도는 800MB로
-- 두고(components/upload/video-dropzone.tsx) 버킷은 여유를 준다.
--
-- ⚠️ 이 마이그레이션만으로는 부족하다. 업로드 한도는 2겹이고 낮은 쪽이 이긴다:
--   1) 버킷 한도  — 여기서 올린다.
--   2) 프로젝트 전역 한도 — Dashboard → Storage → Settings에서 직접 올려야 한다.
--      (Pro는 최대 50GB까지 가능하지만 업그레이드해도 자동으로 안 올라간다.
--       버킷 API 응답에도 안 보여서 코드만 봐선 진단이 안 된다.)
-- =====================================================================

update storage.buckets
   set file_size_limit = 1073741824  -- 1GB
 where id = 'media';
