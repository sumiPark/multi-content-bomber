/** 장면표(writeStoryboard)의 구조 · 말하는 사람 · 마무리 — 이야기형일 때 기본 구조 대신 쓴다. */
export function storyStructure(charLimits: [number, number]): string {
  return `구조와 분량 — 이야기형(계정 설정에 적힌 길이나 "질문 하나" 같은 문구보다 이 기준이 먼저다):
- 브랜드가 "저희"라는 목소리로 이 상품이 왜 이렇게 나왔는지 들려주는 탄생 이야기다. 광고 문구를 읽는 영상이 아니다.
- 길이는 내용이 정한다. 말 전체(tts를 이어 붙인 글자, 띄어쓰기 제외)가 ${charLimits[0]}~${charLimits[1]}자(30~85초) 안이면 된다. 1분을 채우려고 문장을 늘리지 않는다.
- 한 장면은 2~4초(약 15~28자)이고, 한 장면에 말 한 가지만 담는다. 한 편에 이야기 하나만 한다.
- 장면 역할(part)은 아래 뜻으로 쓴다.
  - situation(첫 장면, 첫 3초): 이 상품이 푸는 문제를 시청자에게 묻는 질문 한 문장("~하면 어떻게 될까요?"). 첫 장면 하나만 situation이다. "저희는"으로 시작하지 않는다.
  - knowledge(20~30%): 그 문제가 왜 생기는지 쉬운 말과 비유로 설명하는 상식. 질문 바로 다음에 와도 된다.
  - worry(10~20%): 흔히 하는 해결 방법과 그게 잘 안 되는 이유("물을 더 부으면 될까요?" → "많이 부어도 다 같이 날아가요"). 우리 상품(product) 장면보다 앞에 둔다.
  - product(30~40%): "그래서 저희는 ~부터 찾았어요", "~를 넣었어요", "~로 만들었어요"처럼 저희가 한 선택을 하나씩 말한다. 선택마다 왜 그렇게 했는지 앞의 상식 · 문제와 잇는다. 성분이면 전성분 표기, 과일이면 품종 · 산지까지 구체적으로.
  - difference(10~15%): 담당자가 확정한 우리 차이가 있을 때만 비교 대상과 함께 말한다. 없으면 이 구간을 쓰지 않는다.
  - takeaway(마지막 장면, 4~6초): "그렇게 나온 게 ○○예요"처럼 이 상품이 태어난 한 줄. 상품 이름을 이 장면에서 꼭 말한다. 이 장면 하나로 천천히 끝낸다.
- 앞에서 던진 장면을 끝에서 다시 불러오면 좋다(예: 처음에 날아간 물방울이 마지막에 다시 붙잡힌다).
- 8~12초마다 "그럼 어떻게 했냐면", "근데" 같은 다음 궁금증 문장으로 흐름을 잇는다. 사실을 차례로 읽어 주지 않는다.
- 상품 이름은 뒤에서 처음 말해도 된다(탄생 이야기의 공개). 다만 무슨 종류의 상품인지(토너, 사과 등)는 앞쪽에서 알 수 있게 한다. product_first_scene에 상품 이름을 처음 말하는 장면 번호를 쓴다.
- 마무리: 저장 · 팔로우 요청을 말로 하지 않는다. 요청은 캡션에만 하나 쓴다. 마지막 몇 초에 요청 · 인사 · 정리를 몰아 넣어 급하게 끝내지 않는다.

말하는 사람:
- 이야기 전체를 브랜드가 "저희"로 말한다. 질문 · 상식 장면은 시청자에게 말 거는 말투로 쓰고, product 장면부터 "저희는"이 나온다.
- 저희가 한 선택의 내용은 상품 자료(P) · 확정된 우리 차이(D)에 있는 것만 쓴다. 자료에 없는 개발 과정 · 연구 기간 · 시행착오 · 숫자는 지어내지 않는다. 시도가 안 되는 이유는 널리 알려진 상식으로 말하고, 저희가 실제로 겪은 일처럼 꾸미지 않는다.
${MADE_OR_PICKED}
- 지어낸 인물("제 친구가", "어떤 고객님이"), 사람이 써 본 체험("써 봤는데", "제 피부가"), 지어낸 후기는 쓰지 않는다.
- 장면마다 evidence를 채운다. 상품에 대한 문장은 상품 자료(P), 상식 문장은 상식 카드(K1...)를 먼저 쓰고, 카드에 없는 널리 알려진 원리 · 원료 일반 · 생활 상식은 "일반 상식"이라고 적는다. 우리 차이는 D1...만 쓴다.`;
}

